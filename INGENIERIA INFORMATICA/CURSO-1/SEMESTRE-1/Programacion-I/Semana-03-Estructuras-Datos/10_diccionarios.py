# ¿Qué es un diccionario?

# Un diccionario es una estructura de datos que almacena
# información mediante pares clave-valor.

# A diferencia de una lista, donde accedemos mediante
# posiciones (índices), en un diccionario accedemos
# mediante claves.

# Lista:
# posición -> valor

# Diccionario:
# clave -> valor
